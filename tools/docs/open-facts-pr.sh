#!/bin/sh
# Commit the regenerated facts regions to docs/facts-update and open (or update) one pull
# request. Needs GH_TOKEN and a checkout whose credentials may push. Used by the docs-facts
# workflow after `docs_facts.py generate`; does nothing when no region changed.
set -eu
if git diff --quiet; then
  echo "Every facts region is current."
  exit 0
fi
base="${BASE:-main}"
body="Regenerated by docs-facts from the published releases and the manifests. Review the diff; nothing else changed."
git config user.name "docs-facts"
git config user.email "docs-facts@users.noreply.github.com"
git checkout -B docs/facts-update
git add -u
git commit -q -m "Docs: refresh generated facts"
git push --force origin docs/facts-update
gh pr create --base "$base" --head docs/facts-update --title "Docs: refresh generated facts" --body "$body" \
  || gh pr edit docs/facts-update --body "$body"
